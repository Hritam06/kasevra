"""Escaped, self-contained HTML rendering for V2 reports."""

import html
import os
import tempfile
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from kasevra.exceptions import OperationError, SafetyError
from kasevra.reporting.json_report import REPORT_FORMAT, _validate_json_value


def _render_value(value: Any) -> str:
    if isinstance(value, Mapping):
        if not value:
            return "<p>None recorded.</p>"
        rows = []
        for key in sorted(value):
            rows.append(
                "<tr><th>"
                + html.escape(str(key), quote=True)
                + "</th><td>"
                + _render_value(value[key])
                + "</td></tr>"
            )
        return "<table><tbody>" + "".join(rows) + "</tbody></table>"
    if isinstance(value, (list, tuple)):
        if not value:
            return "<p>None recorded.</p>"
        return (
            "<ul>"
            + "".join("<li>" + _render_value(item) + "</li>" for item in value)
            + "</ul>"
        )
    if value is None:
        return "<span>Not supplied</span>"
    if isinstance(value, bool):
        return "true" if value else "false"
    return html.escape(str(value), quote=True)


def render_v2_html_report(report: Mapping[str, Any]) -> str:
    """Render report data while escaping all supplied values."""
    if not isinstance(report, Mapping) or report.get("report_format") != REPORT_FORMAT:
        raise ValueError("Unsupported V2 report object.")
    _validate_json_value(report)

    sections = (
        ("Collection", report.get("collection")),
        ("Summary", report.get("summary")),
        ("Verification", report.get("verification")),
        ("Baseline comparison", report.get("comparison")),
        ("Digital signature", report.get("signature")),
        ("Chain of custody", report.get("custody")),
    )
    content = []
    for heading, value in sections:
        content.append(
            "<section><h2>"
            + html.escape(heading)
            + "</h2>"
            + _render_value(value)
            + "</section>"
        )
    content.append(
        "<section><h2>Integrity notice</h2><p>"
        + html.escape(str(report.get("integrity_notice", "")), quote=True)
        + "</p></section>"
    )
    return (
        """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>KASEVRA V2 Evidence Report</title>
<style>
:root{color-scheme:dark;font-family:system-ui,sans-serif;background:#101719;color:#e6eeee}
body{max-width:1100px;margin:auto;padding:30px 20px;line-height:1.55}
header,section,footer{margin:20px 0;padding:18px;border:1px solid #304448}
h1,h2{color:#35e0c1}table{width:100%;border-collapse:collapse;overflow-wrap:anywhere}
th,td{text-align:left;vertical-align:top;padding:8px;border-bottom:1px solid #304448}
th{color:#35e0c1;width:28%}code{overflow-wrap:anywhere}
</style></head><body>
<header><h1>KASEVRA</h1><p>Digital Evidence &amp; Integrity Toolkit</p>
<p>Collect with care. Verify with confidence.</p>
<p>Report generated (UTC): """
        + html.escape(str(report.get("generated_utc", "")), quote=True)
        + "</p></header>"
        + "".join(content)
        + """
<footer>Generated by KASEVRA. Review records and limitations.</footer>
</body></html>
"""
    )


def write_v2_html_report(report: Mapping[str, Any], output: Path) -> Path:
    """Create an HTML report without replacing an existing destination."""
    output = Path(os.path.abspath(Path(output).expanduser()))
    if output.is_symlink():
        raise SafetyError("Report output must not be a symbolic link.")
    if output.exists():
        raise SafetyError("Report output already exists; refusing to overwrite it.")
    if not output.parent.is_dir():
        raise OperationError("Report output directory does not exist.")

    content = render_v2_html_report(report)
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=output.parent,
            prefix=".kasevra-v2-report-",
            suffix=".tmp",
            delete=False,
        ) as stream:
            temporary_path = Path(stream.name)
            stream.write(content)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.link(temporary_path, output)
    except FileExistsError as exc:
        raise SafetyError(
            "Report output already exists; refusing to overwrite it."
        ) from exc
    except OSError as exc:
        raise OperationError("V2 HTML report could not be written safely.") from exc
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
    return output
